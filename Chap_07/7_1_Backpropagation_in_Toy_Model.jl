dldω₀(x, y, β₀, β₁, β₂, β₃, ω₀, ω₁, ω₂, ω₃) = Symbolics.derivative(loss(x, y, β₀, β₁, β₂, β₃, ω₀, ω₁, ω₂, ω₃), ω₀)

# ╔═╡ abd5bbaf-8945-4194-8a4e-decabcf1a72e
dldω₀(x, y, β₀, β₁, β₂, β₃, ω₀, ω₁, ω₂, ω₃)

